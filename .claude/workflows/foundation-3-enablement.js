function blockers(review, verify) {
  const lines = []
  for (const m of review.majors) lines.push(`- Review: ${m.title}${m.file ? ` (${m.file})` : ''}: ${clip(m.detail)}`)
  for (const k of verify.checks.filter(k => !k.passed)) lines.push(`- Check failed: ${k.command}: ${clip(k.output)}`)
  for (const a of verify.acceptance.filter(a => a.verdict === 'failed')) lines.push(`- "Done when" not met: ${a.item}: ${clip(a.evidence)}`)
  if (verify.verdict === 'fail') {
    for (const a of verify.acceptance.filter(a => a.verdict === 'not_verified')) lines.push(`- "Done when" could not be verified: ${a.item}: ${clip(a.evidence)}`)
  }
  if (review.verdict !== 'approve' && !review.majors.length) lines.push(`- Review: ${clip(review.summary)}`)
  if (!lines.length) lines.push(`- ${clip(verify.summary)}`)
  return lines.join('\n')
}

// Merges of this workflow happen one after another, in the order they become ready.
let mergeQueue = Promise.resolve()
function oneAtATime(job) {
  const turn = mergeQueue.then(job, job)
  mergeQueue = turn.then(() => null, () => null)
  return turn
}

function finish(p, outcome) {
  log(`${tag(p)}: ${outcome.status}${outcome.pr ? ` (pull request #${outcome.pr})` : ''}${outcome.reason ? `: ${clip(outcome.reason)}` : ''}`)
  return { pbi: tag(p), n: p.n, title: p.title, ...outcome }
}

async function deliver(p) {
  const c = place(p)
  const state = stateOf[p.n] || { n: p.n, state: 'OPEN', pr: 0, prState: 'NONE' }
  if (state.state === 'CLOSED') return finish(p, { status: 'merged', reason: 'the issue was already closed' })

  let pr = state.prState === 'OPEN' ? state.pr : 0
  if (pr) {
    log(`${tag(p)}: continuing with open pull request #${pr}`)
  } else {
    const built = await agent(implementPrompt(p, c, state), {
      label: `implement ${tag(p)}`,
      phase: 'Implement',
      model: p.implement.model,
      effort: p.implement.effort,
      schema: IMPLEMENT_SCHEMA,
    })
    if (!built || built.status !== 'pr_ready' || !built.pr) {
      return finish(p, { status: 'blocked', stage: 'implement', reason: built ? built.reason || built.summary : 'the agent did not finish' })
    }
    pr = built.pr
  }

  let round = 0
  let earlier = ''
  let review
  for (;;) {
    const again = round ? ` (${round + 1})` : ''
    const [r, v] = await parallel([
      () => agent(reviewPrompt(p, c, pr, round, earlier), {
        label: `review ${tag(p)}${again}`,
        phase: 'Review',
        model: p.review.model,
        effort: p.review.effort,
        schema: REVIEW_SCHEMA,
      }),
      () => agent(verifyPrompt(p, c, pr, round), {
        label: `test and validate ${tag(p)}${again}`,
        phase: 'Test and validate',
        model: STAGES.verify.model,
        effort: STAGES.verify.effort,
        schema: VERIFY_SCHEMA,
      }),
    ])
    if (!r || !v) {
      return finish(p, { status: 'blocked', stage: 'checks', pr, reason: `${!r ? 'the review' : 'testing and validation'} did not finish` })
    }
    review = r
    if (r.verdict === 'approve' && v.verdict === 'pass') break
    if (round === MAX_FIX_ROUNDS) {
      return finish(p, { status: 'blocked', stage: 'checks', pr, reason: `still blocked after ${MAX_FIX_ROUNDS} fix rounds. Review: ${r.summary} Validation: ${v.summary}` })
    }
    round += 1
    earlier = blockers(r, v)
    log(`${tag(p)}: fix round ${round} (${r.majors.length} major findings, validation ${v.verdict})`)
    // The first fix goes to the model that wrote the code; a second one goes to a stronger model.
    const fixer = round === 1 ? p.implement : STAGES.fixEscalation
    const fixed = await agent(fixPrompt(p, c, pr, earlier, round), {
      label: `fix ${tag(p)} (${round})`,
      phase: 'Fix',
      model: fixer.model,
      effort: fixer.effort,
      schema: FIX_SCHEMA,
    })
    if (!fixed || fixed.status !== 'fixed') {
      return finish(p, { status: 'blocked', stage: 'fix', pr, reason: fixed ? fixed.reason : 'the agent did not finish' })
    }
  }

  if (!AUTO_MERGE) return finish(p, { status: 'ready', pr, fixRounds: round, minorFindings: review.minors.length })

  const merged = await oneAtATime(() => agent(mergePrompt(p, c, pr, review.minors), {
    label: `merge ${tag(p)}`,
    phase: 'Merge',
    model: STAGES.merge.model,
    effort: STAGES.merge.effort,
    schema: MERGE_SCHEMA,
  }))
  if (!merged || merged.status !== 'merged') {
    return finish(p, { status: 'blocked', stage: 'merge', pr, reason: merged ? merged.reason : 'the agent did not finish' })
  }
  return finish(p, { status: 'merged', pr, fixRounds: round, followUps: merged.followUps || [] })
}

// A PBI starts when every PBI it waits for in this run is merged. No waves, no idle time.
const started = {}
function start(p) {
  if (!started[p.n]) {
    const waitsFor = p.deps.filter(d => inRun.has(d)).map(d => start(byNumber[d]))
    started[p.n] = Promise.all(waitsFor).then(before => {
      const missing = before.find(r => r.status !== 'merged')
      if (missing) return finish(p, { status: 'skipped', reason: `${missing.pbi} did not merge` })
      return deliver(p).catch(error => finish(p, { status: 'blocked', stage: 'workflow', reason: String((error && error.message) || error) }))
    })
  }
  return started[p.n]
}

const results = await Promise.all(ITEMS.map(start))

const mergedNow = results.filter(r => r.status === 'merged' && r.pr).map(r => r.pbi)
let main = null
if (mergedNow.length) {
  main = await agent(mainPrompt(mergedNow), {
    label: 'validate main',
    phase: 'Validate main',
    model: STAGES.validateMain.model,
    effort: STAGES.validateMain.effort,
    schema: MAIN_SCHEMA,
  })
  if (!main) main = { ok: false, checks: [], problems: ['The check of main did not finish.'] }
}

const allMerged = results.every(r => r.status === 'merged')
const allReady = results.every(r => r.status === 'ready' || r.status === 'merged')
return {
  workflow: PLAN.name,
  status: allMerged && (!main || main.ok) ? 'done' : !AUTO_MERGE && allReady ? 'ready_to_merge' : 'needs_attention',
  results,
  main,
}
