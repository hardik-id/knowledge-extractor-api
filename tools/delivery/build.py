#!/usr/bin/env python3
"""Build the delivery workflows in .claude/workflows/ from plan.json and engine.js.

    python3 tools/delivery/build.py

One file per workflow in plan.json. A workflow script can't import anything,
so each file carries its own copy of the engine. Edit engine.js or plan.json
and run this again; never edit the generated files.
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / ".claude" / "workflows"

PHASES = [
    {
        "title": "Prepare",
        "detail": "find the checkout, check the tools, start the shared database",
    },
    {"title": "Implement", "detail": "one agent per PBI, each in its own git worktree"},
    {
        "title": "Review",
        "detail": "code review of the pull request by an agent that has not seen the work",
    },
    {
        "title": "Test and validate",
        "detail": "clean checkout: run the checks, then every Done-when item against the running app",
    },
    {
        "title": "Fix",
        "detail": "only when the review or the validation blocks; two rounds at most",
    },
    {
        "title": "Merge",
        "detail": "one at a time: rebase, squash-merge, file the minor findings",
    },
    {"title": "Validate main", "detail": "full check of main after the merges"},
]


def js(value: object, level: int = 0) -> str:
    """A JavaScript literal: bare keys and single-quoted strings, nothing computed."""
    pad, inner = "  " * level, "  " * (level + 1)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"
    if isinstance(value, list):
        if not any(isinstance(v, (dict, list)) for v in value):
            return "[" + ", ".join(js(v) for v in value) + "]"
        return (
            "[\n" + "".join(f"{inner}{js(v, level + 1)},\n" for v in value) + pad + "]"
        )
    if isinstance(value, dict):
        if not any(isinstance(v, (dict, list)) for v in value.values()):
            return "{ " + ", ".join(f"{k}: {js(v)}" for k, v in value.items()) + " }"
        return (
            "{\n"
            + "".join(f"{inner}{k}: {js(v, level + 1)},\n" for k, v in value.items())
            + pad
            + "}"
        )
    raise TypeError(f"can't write {value!r}")


GENERATED = "// GENERATED by tools/delivery/build.py from plan.json and engine.js."


def main() -> None:
    plan = json.loads((HERE / "plan.json").read_text())
    engine = (HERE / "engine.js").read_text()
    # An item belongs to one repository ("kind": api or ui) and is known by its issue number there.
    items = {(item.get("kind", "api"), item["n"]): item for item in plan["items"]}

    assigned = [
        (workflow.get("kind", "api"), n)
        for workflow in plan["workflows"]
        for n in workflow["items"]
    ]
    if sorted(assigned) != sorted(items):
        sys.exit(
            "plan.json: every item must be in exactly one workflow of its own kind"
        )
    for (kind, n), item in items.items():
        for dep in item["deps"]:
            if (kind, dep) not in items or dep >= n:
                sys.exit(
                    f"plan.json: {kind} item {n} depends on {dep}, which is unknown or comes later"
                )

    OUT.mkdir(parents=True, exist_ok=True)
    wanted = set()
    for workflow in plan["workflows"]:
        kind = workflow.get("kind", "api")
        meta = {
            "name": workflow["name"],
            "description": workflow["description"],
            "whenToUse": workflow["whenToUse"],
            "phases": PHASES,
        }
        entries = []
        for n in workflow["items"]:
            item = items[(kind, n)]
            tier = plan["tiers"][item["tier"]]
            entry = {
                "n": n,
                "slug": item["slug"],
                "title": item["title"],
                "deps": item["deps"],
                "implement": tier["implement"],
                "review": tier["review"],
            }
            if "escalate" in tier:
                entry["escalate"] = tier["escalate"]
            entries.append(entry)
        data = {
            "name": workflow["name"],
            "index": workflow["index"],
            "kind": kind,
            "repo": plan["repos"][kind],
            "needsApi": workflow.get("needsApi", kind == "ui"),
            "maxFixRounds": plan["maxFixRounds"],
            "stages": plan["stages"],
            "items": entries,
        }
        text = (
            f"export const meta = {js(meta)}\n\n"
            f"{GENERATED}\n"
            "// Don't edit this file: change those two and build again.\n\n"
            f"const PLAN = {js(data)}\n\n"
            f"{engine}"
        )
        path = OUT / f"{workflow['name']}.js"
        path.write_text(text)
        wanted.add(path.name)
        print(f"wrote {path.relative_to(OUT.parent.parent)}")

    for stale in OUT.glob("*.js"):
        if stale.name not in wanted and GENERATED in stale.read_text():
            stale.unlink()
            print(f"removed {stale.name}")


if __name__ == "__main__":
    main()
